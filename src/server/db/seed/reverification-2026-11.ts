/**
 * Moves the re-verified sources, and the held sources whose data this release
 * corrects, to the November 2026 verification time.
 */
export function withNovember2026SourceReverification<
  T extends { id?: string; updatedAt?: Date | null; verifiedAt: Date },
>(rows: readonly T[]): T[] {
  return rows.map((row) =>
    row.id !== undefined &&
    (november2026ReverifiedSourceIds.has(row.id) ||
      november2026CorrectedSourceIds.has(row.id))
      ? {
          ...row,
          updatedAt: november2026ReverificationTimestamp,
          verifiedAt: november2026ReverificationTimestamp,
        }
      : row,
  );
}
